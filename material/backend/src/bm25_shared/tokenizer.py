_TOKENIZE_RE = re.compile(r"[a-zäöüß0-9]+")

# Cistem is German-specific and consistently outperforms Snowball German on IR tasks.
# case_insensitive=True because we've already lowercased; this skips Cistem's own
# capitalization heuristic which expects mixed case.
_STEMMER = Cistem(case_insensitive=True)


def tokenize(text: str) -> list[str]:
    """Tokenize text: lowercase, stopword filter, decompound, then Cistem stem."""
    tokens = _TOKENIZE_RE.findall(text.lower())
    filtered = [t for t in tokens if t not in GERMAN_STOPWORDS and len(t) > 1]
    pieces = [piece for t in filtered for piece in decompound(t)]
    return [_STEMMER.stem(p) for p in pieces]
